def assign_positions(seed):
    """Balance correct-answer positions inside every topic (difference <= 1)."""
    rng = random.Random(seed)
    result = [None] * len(QS)
    by_topic = collections.defaultdict(list)
    for idx, q_ in enumerate(QS):
        by_topic[q_["topic"]].append(idx)
    for t in sorted(by_topic):
        idxs = by_topic[t]
        fixed = collections.Counter(QS[i]["_fixed"][1] for i in idxs if QS[i]["_fixed"])
        free = [i for i in idxs if not QS[i]["_fixed"]]
        base, rem = divmod(len(idxs), 4)
        order = [0, 1, 2, 3]
        rng.shuffle(order)
        targets = {p: base + (1 if k < rem else 0) for k, p in enumerate(order)}
        need = {p: max(0, targets[p] - fixed.get(p, 0)) for p in range(4)}
        pos = []
        for p in range(4):
            pos += [p] * need[p]
        while len(pos) < len(free):
            pos.append(rng.randrange(4))
        pos = pos[:len(free)]
        rng.shuffle(pos)
        for i, pp in zip(free, pos):
            wr = list(QS[i]["_wrong"])
            rng.shuffle(wr)
            result[i] = (wr[:pp] + [QS[i]["_correct"]] + wr[pp:], pp)
        for i in idxs:
            if QS[i]["_fixed"]:
                opts, ans = QS[i]["_fixed"]
                result[i] = (list(opts), ans)
    return result

def score(result):
    per = collections.defaultdict(collections.Counter)
    for q_, (opts, ans) in zip(QS, result):
        per[q_["topic"]][ans] += 1
    s = 0
    for t, c in per.items():
        vals = [c.get(i, 0) for i in range(4)]
        s += max(vals) - min(vals)
    # penalise runs of 3 identical answers in a row within a topic
    runs = 0
    last = {}
    streak = {}
    for q_, (opts, ans) in zip(QS, result):
        t = q_["topic"]
        if last.get(t) == ans:
            streak[t] += 1
            if streak[t] >= 3:
                runs += 1
        else:
            streak[t] = 1
        last[t] = ans
    return s * 10 + runs

