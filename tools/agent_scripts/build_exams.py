def build_bank():
    rng = random.Random(20260929)
    cards, questions = [], []
    for i, c in enumerate(CARDS, 1):
        topic, level, title, body_, key, src, conf = c[:7]
        exam = c[7] if len(c) > 7 else BOTH
        d = {"id": f"roadtest-card-{i:03d}", "topic": topic, "level": level, "title": title, "body": body_}
        if key:
            d["key"] = key
        d.update({"exam": exam, "src": src, "confidence": conf})
        cards.append(d)
    counters = {}
    # spread correct positions evenly: shuffle a balanced list of target indexes
    targets = [i % 4 for i in range(len(QS))]
    rng.shuffle(targets)
    for n, (topic, level, exam, q, opts, explain, tip, src, conf, notes) in enumerate(QS):
        counters[topic] = counters.get(topic, 0) + 1
        correct = opts[0]
        wrong = opts[1:]
        rng.shuffle(wrong)
        pos = targets[n]
        options = wrong[:pos] + [correct] + wrong[pos:]
        d = {"id": f"roadtest-{topic}-{counters[topic]:03d}", "topic": topic, "level": level, "exam": exam,
             "q": q, "options": options, "answer": pos, "explain": explain}
        if tip:
            d["tip"] = tip
        d.update({"src": src, "confidence": conf})
        if notes:
            d["notes"] = notes
        questions.append(d)
    ids = sorted(used_sources({"c": cards, "q": questions}, set()), key=lambda s: int(s[1:]))
    return {"module": "roadtest", "updated": UPDATED, "sources": {k: SOURCES[k] for k in ids},
            "cards": cards, "questions": questions}


