def main():
    rng = random.Random(20260929)
    cards = []
    for i, (lvl, title, body, key, src, conf, notes) in enumerate(CARDS, 1):
        c = {"id": "signbasics-card-%03d" % i, "topic": TOPIC, "level": lvl, "title": title, "body": body,
             "key": key, "src": src, "confidence": conf}
        if notes:
            c["notes"] = notes
        cards.append(c)
    qs = []
    pos = collections.Counter()
    for i, (lvl, exam, q, right, wrong, explain, tip, src, conf, notes) in enumerate(QUESTIONS, 1):
        # choose the least used position among a random order, so positions stay balanced but unpredictable
        order = [0, 1, 2, 3]
        rng.shuffle(order)
        ans = min(order, key=lambda k: pos[k])
        opts = list(wrong)
        rng.shuffle(opts)
        opts.insert(ans, right)
        pos[ans] += 1
        item = {"id": "signbasics-%s-%03d" % (TOPIC, i), "topic": TOPIC, "level": lvl, "exam": exam, "q": q,
                "options": opts, "answer": ans, "explain": explain}
        if tip:
            item["tip"] = tip
        item.update({"src": src, "confidence": conf, "notes": notes or ""})
        qs.append(item)
    doc = {"module": "signbasics", "updated": "2026-09-29",
           "sources": {k: SOURCES[k] for k in USED},
           "cards": cards, "questions": qs}
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("wrote", OUT, len(cards), "cards", len(qs), "questions", dict(sorted(pos.items())))


if __name__ == "__main__":
    main()
